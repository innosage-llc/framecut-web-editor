import { Clip, Subtitle } from '../types';
import { generateId } from '../utils';
import type { TranscriptSegment } from './transcriber';
import type { SubtitleCue } from './subtitleFormats';

export const DEFAULT_SUBTITLE_STYLE: Partial<Subtitle> = {
  x: 50, y: 80,
  color: '#ffffff', backgroundColor: 'rgba(0,0,0,0.5)', fontFamily: 'Arial', fontWeight: 'bold', fontStyle: 'normal',
};

type Word = { start: number; end: number; text: string };

const cleanWords = (words: Word[] | undefined, max: number): Word[] | undefined => {
  if (!Array.isArray(words)) return undefined;
  return words
    .filter(w => w && typeof w.text === 'string' && w.text.trim() !== '' && Number.isFinite(w.start))
    .map(w => {
      const a = Math.max(0, w.start);
      const b = Number.isFinite(w.end) && w.end >= a ? w.end : a;
      return { text: w.text, start: Math.min(max, a), end: Math.min(max, b) };
    });
};

/** Words whose midpoint lies in [a, b], joined back into text. */
const wordsIn = (words: Word[], a: number, b: number) => words.filter(w => { const m = (w.start + w.end) / 2; return m >= a && m <= b; });
const joinWords = (words: Word[]) => words.map(w => w.text).join('').replace(/\s+/g, ' ').trim();

/**
 * Clean transcript segments into valid cues inside [0, duration] that never overlap each
 * other. Engines can return overlapping segments (Whisper chunk stitching, a missing end
 * timestamp, or one source range mapped twice); earlier-starting cues win and later ones are
 * fitted into the free time, the same way generated cues are fitted around manual ones.
 */
export function segmentsToCues(segments: TranscriptSegment[], duration: number): SubtitleCue[] {
  const max = duration > 0 ? duration : Infinity;
  const cues = (segments || [])
    .filter(s => s && typeof s.text === 'string' && Number.isFinite(s.start) && Number.isFinite(s.end))
    .map(s => {
      const c: SubtitleCue = { start: Math.max(0, s.start), end: Math.min(max, s.end), text: s.text.trim() };
      const w = cleanWords(s.words, max);
      if (w && w.length) {
        c.words = w;
        // A missing end timestamp gets stretched (to the chunk or media end); words say when speech stops.
        const lastWord = Math.max(...w.map(x => x.end));
        if (lastWord > c.start && lastWord < c.end) c.end = lastWord;
      }
      return c;
    })
    .filter(c => c.text !== '' && c.end > c.start)
    .sort((a, b) => a.start - b.start || a.end - b.end);
  const out: SubtitleCue[] = [];
  for (const c of cues) out.push(...fitCuesAroundManual([c], out));
  return out.sort((a, b) => a.start - b.start);
}

export const cueToSubtitle = (c: SubtitleCue, autoGenerated: boolean): Subtitle =>
  ({ id: generateId(), ...DEFAULT_SUBTITLE_STYLE, text: c.text, start: c.start, end: c.end, autoGenerated } as Subtitle);

/** Regenerate: drop previous auto cues, keep every manual/edited cue, add the new auto cues. */
export function replaceAutoSubtitles(existing: Subtitle[], cues: SubtitleCue[]): Subtitle[] {
  const manual = existing.filter(s => !s.autoGenerated);
  return [...manual, ...fitCuesAroundManual(cues, manual).map(c => cueToSubtitle(c, true))];
}

/** Shortest generated cue worth keeping after trimming around manual cues (seconds). */
export const MIN_FITTED_CUE_SECONDS = 0.3;

/**
 * Manual cues win: a new cue that collides with one is trimmed to the longest free part
 * of its span, or dropped if what's left is shorter than MIN_FITTED_CUE_SECONDS.
 * When the cue has word timings, its text is cut to the words inside the kept part (a word
 * counts where its midpoint falls); a part with no words is dropped. Cues without word
 * timings keep their text (the engine gave nothing finer to cut by).
 */
export function fitCuesAroundManual(cues: SubtitleCue[], manual: { start: number; end: number }[]): SubtitleCue[] {
  const blocks = [...manual].sort((a, b) => a.start - b.start);
  const out: SubtitleCue[] = [];
  for (const c of cues) {
    let pieces: [number, number][] = [[c.start, c.end]];
    for (const m of blocks) {
      pieces = pieces.flatMap(([a, b]): [number, number][] => {
        if (m.end <= a || m.start >= b) return [[a, b]];
        const r: [number, number][] = [];
        if (m.start > a) r.push([a, m.start]);
        if (m.end < b) r.push([m.end, b]);
        return r;
      });
    }
    const untouched = pieces.length === 1 && pieces[0][0] === c.start && pieces[0][1] === c.end;
    if (untouched) { out.push(c); continue; }
    const ok = pieces
      .filter(([a, b]) => b - a >= MIN_FITTED_CUE_SECONDS - 1e-9)
      .filter(([a, b]) => !c.words || wordsIn(c.words, a, b).length > 0)
      .sort((x, y) => (y[1] - y[0]) - (x[1] - x[0]));
    const best = ok[0];
    if (!best) continue;
    if (!c.words) { out.push({ ...c, start: best[0], end: best[1] }); continue; }
    const kept = wordsIn(c.words, best[0], best[1]);
    out.push({ start: best[0], end: best[1], text: joinWords(kept), words: kept });
  }
  return out;
}

/**
 * Transcripts are in main-video SOURCE time. Map them onto the timeline through the main
 * clips (trims/splits/speed); speech inside cut-out ranges is dropped.
 */
export function mapSourceSegmentsToTimeline(segments: TranscriptSegment[], clips: Clip[]): TranscriptSegment[] {
  const mains = clips.filter(c => c.mediaType === 'main');
  if (mains.length === 0) return segments;
  const out: TranscriptSegment[] = [];
  for (const s of segments) {
    for (const c of mains) {
      const a = Math.max(s.start, c.sourceStart), b = Math.min(s.end, c.sourceEnd);
      if (b <= a) continue;
      const speed = c.speed || 1;
      const map = (t: number) => c.offset + (t - c.sourceStart) / speed;
      const seg: TranscriptSegment = { text: s.text, start: map(a), end: map(b) };
      if (s.words) {
        // Keep only the words spoken inside this clip; the text follows when any were cut.
        const inClip = s.words.filter(w => { const m = (w.start + w.end) / 2; return m >= c.sourceStart && m <= c.sourceEnd; })
          .map(w => ({ text: w.text, start: map(Math.max(w.start, c.sourceStart)), end: map(Math.min(w.end, c.sourceEnd)) }));
        if (inClip.length === 0) continue;
        seg.words = inClip;
        if (inClip.length !== s.words.length) seg.text = joinWords(inClip);
      }
      out.push(seg);
    }
  }
  return out;
}
